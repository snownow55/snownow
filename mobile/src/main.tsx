import { createRoot } from "react-dom/client";
import { Suspense, useEffect, useState } from "react";
import { AuthProvider } from "../../components/auth-provider";
import { AppFooter } from "../../components/app-footer";
import { AccountDeletionForm } from "../../components/account-deletion-form";
import Home from "../../app/(app)/page";
import Resort from "../../app/(app)/resort/[name]/page";
import Post from "../../app/(app)/post/page";
import Settings from "../../app/(app)/settings/page";
import Terms from "../../app/(app)/terms/page";
import Privacy from "../../app/(app)/privacy/page";
import Contact from "../../app/(app)/contact/page";
import Access from "../../app/(app)/access/page";
import { NativeAuthForm } from "./auth-form";
import { initializeNavigation, useLocation } from "./next/navigation";
import { initializeApi } from "./api";
import { initializePlatform } from "./platform";
import { supabase } from "./supabase";
import "./styles.css";
initializeNavigation(); initializeApi(); initializePlatform();
function App() {
  const location = useLocation(); const path = location.split("|")[0].split("?")[0];
  const [notice, setNotice] = useState("");
  useEffect(() => { const listener = (event: Event) => setNotice((event as CustomEvent<string>).detail); window.addEventListener("snow-native-error", listener); return () => window.removeEventListener("snow-native-error", listener); }, []);
  let screen;
  if (path === "/") screen = <Home />;
  else if (path.startsWith("/resort/")) screen = <Resort key={path} />;
  else if (path === "/post") screen = <Post />;
  else if (path === "/settings") screen = <Settings />;
  else if (path === "/terms") screen = <Terms />;
  else if (path === "/privacy") screen = <Privacy />;
  else if (path === "/contact") screen = <Contact />;
  else if (path === "/access") screen = <Access />;
  else if (path === "/account/delete") screen = <AccountDeletionForm available={Boolean(supabase)} />;
  else if (path === "/login") screen = <NativeAuthForm mode="login" />;
  else if (path === "/signup") screen = <NativeAuthForm mode="signup" />;
  else if (path === "/forgot-password") screen = <NativeAuthForm mode="forgot" />;
  else if (path === "/reset-password") screen = <NativeAuthForm mode="reset" />;
  else screen = <main className="ui-page p-5">ページが見つかりません。</main>;
  return <AuthProvider>{notice && <p role="alert" className="bg-accent-soft p-3">{notice}</p>}<Suspense fallback={<p>読み込み中…</p>}><div key={location.split("|")[1]}>{screen}</div></Suspense><AppFooter /></AuthProvider>;
}
createRoot(document.getElementById("root")!).render(<App />);
